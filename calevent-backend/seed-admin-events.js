const seedAdminEvents = async () => {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log('✅ Connected to MongoDB');

    // Clear existing admin events (optional)
    const deleteResult = await Event.deleteMany({ createdBy: 'admin' });
    console.log(`🗑️  Deleted ${deleteResult.deletedCount} existing admin events`);

    // Insert new admin events
    const result = await Event.insertMany(adminEvents);
    console.log(`✅ Successfully seeded ${result.length} admin events`);

    console.log('\n📊 Events by Category:');
    const categories = adminEvents.reduce((acc, event) => {
      acc[event.category] = (acc[event.category] || 0) + 1;
      return acc;
    }, {});
    console.table(categories);

    console.log('\n🏷️  Events by Tag:');
    const tags = adminEvents.reduce((acc, event) => {
      acc[event.tag] = (acc[event.tag] || 0) + 1;
      return acc;
    }, {});
    console.table(tags);

    process.exit(0);
  } catch (error) {
    console.error('❌ Error seeding admin events:', error);
    process.exit(1);
  }
};

seedAdminEvents();
